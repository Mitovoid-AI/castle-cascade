// Plays every level with the greedy bot and bakes move counts into js/level-table.js.
// Usage: node tools/tune.js [count=1500] [runs=8]
const { Worker, isMainThread, parentPort, workerData } = require('worker_threads');
const path = require('path');
const fs = require('fs');

const quant = (arr, q) => { const a = arr.slice().sort((x, y) => x - y); return a[Math.min(a.length - 1, Math.floor(q * a.length))]; };

function movesFor(n, kind, used) {
  const won = used.filter((x) => x != null);
  const all = used.map((x) => (x == null ? 99 : x));
  const med = quant(all, 0.5), p75 = quant(all, 0.75), max = Math.max(...won);
  let m;
  if (n <= 15) m = Math.ceil(max * 1.5) + 4;
  else if (kind === 2) m = Math.ceil(med * 1.2) + 1;
  else if (kind === 1) m = Math.ceil(med * 1.3) + 1;
  else if (n % 10 === 1) m = Math.ceil(p75 * 1.6) + 2;
  else m = Math.ceil(p75 * (n < 100 ? 1.45 : 1.35)) + 2;
  return Math.max(12, Math.min(55, m));
}

if (isMainThread) {
  const COUNT = +(process.argv[2] || 1500), RUNS = +(process.argv[3] || 8), W = 4;
  const t0 = Date.now();
  const table = new Array(COUNT);
  const info = new Array(COUNT);
  let done = 0, finished = 0;
  for (let w = 0; w < W; w++) {
    const worker = new Worker(__filename, { workerData: { w, W, COUNT, RUNS } });
    worker.on('message', (msg) => {
      table[msg.n - 1] = [msg.moves, msg.salt];
      info[msg.n - 1] = msg;
      if (++done % 100 === 0) console.log('levels', done, 's', ((Date.now() - t0) / 1000).toFixed(0));
    });
    worker.on('exit', () => {
      if (++finished < W) return;
      const out = '/* Generated by tools/tune.js: [moves, salt] per level, from greedy-bot playthroughs. */\n' +
        '(function (r) { r.CC_LEVEL_TABLE = ' + JSON.stringify(table) + '; })(typeof window !== \'undefined\' ? window : globalThis);\n';
      fs.writeFileSync(path.join(__dirname, '..', 'js', 'level-table.js'), out);
      fs.writeFileSync(path.join(__dirname, 'tune-report.json'), JSON.stringify(info));
      const moves = table.map((x) => x[0]);
      const salts = table.filter((x) => x[1] > 0).length;
      const bad = info.filter((x) => x.wins < x.runs * 0.6).map((x) => x.n);
      console.log({ secs: (Date.now() - t0) / 1000, minMoves: Math.min(...moves), maxMoves: Math.max(...moves), avg: (moves.reduce((a, b) => a + b, 0) / moves.length).toFixed(1), reseeded: salts, weak: bad.length, weakList: bad.slice(0, 30) });
    });
  }
} else {
  const L = require('../js/levels.js');
  const bot = require('./bot.js');
  const { w, W, COUNT, RUNS } = workerData;
  for (let n = 1 + w; n <= COUNT; n += W) {
    let best = null;
    for (let salt = 0; salt < 6; salt++) {
      const lvl = L.gen(n, salt);
      const used = [];
      for (let k = 0; k < RUNS; k++) used.push(bot.play(lvl, (n * 7919 + salt * 104729 + k * 31) >>> 0, 90));
      const wins = used.filter((x) => x != null).length;
      const all = used.map((x) => (x == null ? 99 : x));
      const med = quant(all, 0.5);
      const cand = { n, salt, kind: lvl.kind, runs: RUNS, wins, med, used };
      const ok = wins >= Math.ceil(RUNS * 0.75) && med <= 40;
      if (!best || (ok && !best.ok) || (ok === best.ok && (wins > best.wins || (wins === best.wins && med < best.med)))) best = Object.assign(cand, { ok });
      if (ok) break;
    }
    best.moves = best.wins ? movesFor(n, best.kind, best.used) : L.gen(n, best.salt).estimate;
    parentPort.postMessage(best);
  }
}
